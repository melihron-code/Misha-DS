// Generates src/components/icons/*.jsx from an SVG export of the Figma icons.
// usage: npm run icons   (reads scripts/icons.figma.json: { "figma-name": "<svg …>" }, exported from Figma)
//
// Optimizing: keeps only the <path d>, drops width/height/fill/xmlns and comments,
// keeps the viewBox. Non-square viewBoxes are padded to a centered square, so
// `size` always sets a square box. Fill becomes currentColor (follows text color).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const src = process.argv[2] || path.join(process.cwd(), 'scripts/icons.figma.json')
const out = path.join(process.cwd(), 'src/components/icons')
mkdirSync(out, { recursive: true })
const svgs = JSON.parse(readFileSync(src, 'utf8'))

const pascal = s => s.split(/[-_ ]/).map(w => w[0].toUpperCase() + w.slice(1)).join('')
const names = []

for (const [figmaName, svg] of Object.entries(svgs)) {
  const [, , , vw, vh] = svg.match(/viewBox="(([\d.-]+) ([\d.-]+) ([\d.-]+) ([\d.-]+))"/).slice(1).map(Number)
  const side = Math.max(vw, vh)
  const viewBox = [-(side - vw) / 2, -(side - vh) / 2, side, side].map(n => +n.toFixed(3)).join(' ')
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1])
  const name = pascal(figmaName) + 'Icon'
  names.push({ name, figmaName })
  writeFileSync(path.join(out, name + '.jsx'), `// Figma: Icon "${figmaName}". TEMPORARY: Apple SF Symbol outline, replace before public launch (SF Symbols licence).
import Svg from './Svg'

export default function ${name}(props) {
  return (
    <Svg viewBox="${viewBox}" {...props}>
${paths.map(d => `      <path d="${d}" />`).join('\n')}
    </Svg>
  )
}
`)
}

writeFileSync(path.join(out, 'index.js'), `// Generated by scripts/build-icons.mjs (npm run icons). Do not edit by hand.
// All icons are TEMPORARY SF Symbols outlines (see NOTES.md).
${names.map(n => `import ${n.name} from './${n.name}'`).join('\n')}

export { ${names.map(n => n.name).join(', ')} }

// Figma name → component, for <Icon name="…" />.
export const ICONS = {
${names.map(n => `  '${n.figmaName}': ${n.name},`).join('\n')}
}
`)
console.log('wrote', names.map(n => n.name).join(', '))
